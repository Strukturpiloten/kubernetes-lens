/// Explicit output syntax.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OutputFormat {
    /// Deterministic YAML document stream.
    Yaml,
    /// Strict deterministic JSON.
    Json,
}
/// Explicit JSON collection shape.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum JsonShape {
    /// Exactly one native document.
    SingleResource,
    /// A generic Kubernetes List.
    KubernetesList,
}
/// Explicit native validation operation; never inferred from source or output origin.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum NativeValidationIntent {
    /// Operation-dependent rules remain unverified and produce safe findings.
    #[default]
    Unspecified,
    /// Validate the reviewed create-specific rules, without executing a request.
    Create,
}
/// Native source intent independent of source origin.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OutputIntent {
    /// Retain supplied observations under the same target/opaque/protected checks.
    PreserveObservation,
    /// Retain observations unless explicitly edited.
    PreserveDocument,
    /// Remove only recognized server-owned fields with findings.
    AuthoredIntent,
}
/// No synthetic placeholder output exists.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ProtectedOutput {
    /// Refuse any protected/private opaque payload.
    Deny,
    /// Explicitly authorize actual native payload bytes.
    Include,
}
/// Opaque preservation is separate from typed/native admission.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum OpaqueFieldPolicy {
    /// Fail when field availability cannot be established.
    Block,
    /// Explicitly preserve with private warnings at unadmitted subtree boundaries.
    /// Resource warnings retain source-document paths and enclosing List coordinates.
    PreserveWithFinding,
}
/// Native wrapper retention is an explicit caller decision.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CollectionOutput {
    /// Keep source List wrappers and metadata/order.
    PreserveWrappers,
    /// Emit native items in a deterministic stream.
    Flatten,
}
/// Explicit private-output, admission, and intent policies.
#[derive(Clone, Debug)]
pub struct GenerationOptions {
    /// Optional operation ceiling; it can only lower retained/default processing limits.
    pub processing: Option<NativeProcessingLimits>,
    /// Default denies private values.
    pub protected_output: ProtectedOutput,
    /// Default blocks opaque availability.
    pub opaque_fields: OpaqueFieldPolicy,
    /// Strict JSON shape.
    pub json_shape: JsonShape,
    /// Explicit output intent.
    pub intent: OutputIntent,
    /// Native operation context, independent of output intent and source origin.
    pub validation_intent: NativeValidationIntent,
    /// Explicit YAML/JSON collection policy.
    pub collections: CollectionOutput,
}
impl Default for GenerationOptions {
    fn default() -> Self {
        Self {
            processing: None,
            protected_output: ProtectedOutput::Deny,
            opaque_fields: OpaqueFieldPolicy::Block,
            json_shape: JsonShape::KubernetesList,
            intent: OutputIntent::PreserveDocument,
            validation_intent: NativeValidationIntent::Unspecified,
            collections: CollectionOutput::PreserveWrappers,
        }
    }
}
/// Explicit private artifact access token.
#[derive(Clone, Copy, Debug)]
pub struct ExplicitArtifactAccess(());
impl ExplicitArtifactAccess {
    /// Deliberately authorize raw generated bytes.
    #[must_use]
    pub const fn explicitly_allow_raw_artifact() -> Self {
        Self(())
    }
}
/// Generated bytes remain private and do not imply compatibility or deployment.
pub struct GeneratedArtifact {
    format: OutputFormat,
    bytes: Arc<[u8]>,
    findings: Vec<Finding>,
}
impl GeneratedArtifact {
    /// Selected syntax.
    #[must_use]
    pub const fn format(&self) -> OutputFormat {
        self.format
    }
    /// Structured outcomes, never source values.
    #[must_use]
    pub fn findings(&self) -> &[Finding] {
        &self.findings
    }
    /// Reveal native bytes only after explicit authorization.
    #[must_use]
    pub fn reveal_bytes(&self, _access: &ExplicitArtifactAccess) -> &[u8] {
        &self.bytes
    }
}
impl fmt::Debug for GeneratedArtifact {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("GeneratedArtifact")
            .field("format", &self.format)
            .field("byte_len", &self.bytes.len())
            .field("findings", &self.findings)
            .finish_non_exhaustive()
    }
}
fn validate_wrapper(list: &crate::model::ListDocument, target: &TargetProfile, findings: &mut ProcessingReport) {
    let processing = findings.processing().clone();
    if findings.failed() || processing.work(1, Phase::Validation).is_err() {
        return;
    }
    let root_lookup_work = list
        .original
        .as_mapping()
        .map_or(Some(0), |entries| entries.len().checked_mul(5));
    let Some(root_lookup_work) = root_lookup_work else {
        processing.fail(Phase::Validation);
        return;
    };
    if processing.work(root_lookup_work, Phase::Validation).is_err() {
        return;
    }
    if let Some(metadata) = list.original.get("metadata") {
        if let Some(entries) = metadata.as_mapping() {
            for (key, node) in entries {
                if findings.failed()
                    || processing.work(1, Phase::Validation).is_err()
                    || processing.work(key.len(), Phase::Validation).is_err()
                {
                    return;
                }
                let valid = match key.as_str() {
                    "resourceVersion" | "selfLink" | "continue" => {
                        matches!(node.value, TreeValue::String(_) | TreeValue::Null)
                    }
                    "remainingItemCount" => {
                        matches!(&node.value, TreeValue::Number(value) if value.parse::<u64>().is_ok())
                            || node.value == TreeValue::Null
                    }
                    _ => true,
                };
                if !valid {
                    findings.push(wrapper_finding(
                        list,
                        FindingCode::NativeFieldInvalid,
                        Phase::Validation,
                        FieldPath(vec!["metadata".into(), key.clone()]),
                        true,
                    ));
                    if findings.failed() {
                        return;
                    }
                }
            }
        } else {
            findings.push(wrapper_finding(
                list,
                FindingCode::NativeFieldInvalid,
                Phase::Validation,
                FieldPath(vec!["metadata".into()]),
                true,
            ));
        }
    }
    if findings.failed() {
        return;
    }
    for name in ["apiVersion", "kind"] {
        let bytes = list.original.get(name).and_then(TreeNode::as_str).map_or(0, str::len);
        if processing.payload(bytes, Phase::Validation).is_err() {
            return;
        }
    }
    let Ok(mut gvk) = crate::model::tree_gvk(&list.original) else {
        return;
    };
    if gvk.group.is_none() && gvk.version == "v1" && gvk.kind == "List" {
        return;
    }
    if let Some(kind) = gvk.kind.strip_suffix("List") {
        if processing.payload(kind.len(), Phase::Validation).is_err() {
            return;
        }
        gvk.kind = kind.to_owned();
    }
    if declaration(&gvk).is_some_and(|decl| !(decl.first..=decl.last).contains(&target.kubernetes.minor()))
        || declaration(&gvk).is_none() && crate::capability::builtin_scope(&gvk).is_some()
    {
        findings.push(wrapper_finding(
            list,
            FindingCode::UnavailableApi,
            Phase::Validation,
            FieldPath::default(),
            true,
        ));
    }
    crate::capability::source_field_findings(
        &list.original,
        &gvk,
        target,
        &processing,
        Phase::Validation,
        &mut WrapperFindingSink { list, findings },
    );
}
/// Validate current resources and every retained List against the explicit target.
#[must_use]
pub fn validate_for_target(resources: &ResourceSet, target: &TargetProfile) -> Vec<Finding> {
    validate_for_target_with_intent(resources, target, NativeValidationIntent::Unspecified)
}
/// Validate the same effective native trees with explicitly supplied operation context.
/// This does not establish API-server conformance or authorize execution.
#[must_use]
pub fn validate_for_target_with_intent(
    resources: &ResourceSet,
    target: &TargetProfile,
    intent: NativeValidationIntent,
) -> Vec<Finding> {
    validate_in(resources, target, intent, resources.operation(None))
}
/// Validate under an explicitly lower operation ceiling without changing native source evidence.
/// # Errors
/// Violations and limits are returned as structured findings, never server-validation claims.
#[must_use]
pub fn validate_for_target_with_limits(
    resources: &ResourceSet,
    target: &TargetProfile,
    intent: NativeValidationIntent,
    limits: &NativeProcessingLimits,
) -> Vec<Finding> {
    validate_in(resources, target, intent, resources.operation(Some(*limits)))
}
pub(crate) fn validate_in(
    resources: &ResourceSet,
    target: &TargetProfile,
    intent: NativeValidationIntent,
    processing: NativeOperationBudget,
) -> Vec<Finding> {
    let construction = resources.encoding(Some(target), processing.clone());
    let construction = crate::registry::EncodeContext {
        budget: construction.budget.for_phase(Phase::Validation),
        ..construction
    };
    let mut findings = ProcessingReport::new(processing, Phase::Validation);
    findings.extend(target.findings());
    resources.identity_findings_into(false, Some(&construction), &mut findings);
    for list in &resources.lists {
        if findings.failed() {
            break;
        }
        validate_wrapper(list, target, &mut findings);
    }
    for document in &resources.documents {
        if findings.failed() {
            break;
        }
        let context = construction.for_source(*document.evidence.limits());
        let tree = match document.current_tree_in(Some(target), Some(&context)) {
            Ok(tree) => tree,
            Err(error) => {
                if error.code == FindingCode::MergeConflict {
                    let mut native =
                        Finding::error(FindingCode::NativeFieldInvalid, Phase::Validation).for_resource(document.id);
                    native.path.clone_from(&error.path);
                    native.source = error.source;
                    findings.push(native);
                }
                findings.push(error.for_resource(document.id));
                continue;
            }
        };
        let identity = match crate::model::identity_in(
            &tree,
            document.original_identity.scope,
            findings.processing(),
            Phase::Validation,
        ) {
            Ok(identity) => identity,
            Err(error) => {
                findings.push(error.for_resource(document.id));
                continue;
            }
        };
        validate_api(&identity, document.id, target, &mut findings);
        validate_source_fields(&tree, &identity.gvk, document.id, target, &mut findings);
        if let Some(capability) = &document.capability {
            if target.kubernetes < capability.api_since
                || capability
                    .api_removed
                    .is_some_and(|removed| target.kubernetes >= removed)
            {
                findings.push(Finding::error(FindingCode::UnavailableApi, Phase::Validation).for_resource(document.id));
            }
            for field in capability.fields {
                if findings.failed() {
                    break;
                }
                if field_nodes(&tree, field.path).is_empty() {
                    continue;
                }
                let path = FieldPath::parse(field.path).ok();
                let code = if target.kubernetes < field.since
                    || field.removed.is_some_and(|removed| target.kubernetes >= removed)
                {
                    Some(FindingCode::UnavailableField)
                } else if field.feature_gate.is_some_and(|gate| {
                    target.feature_gates.resolve(gate, target.kubernetes) != Ok(FeatureGateState::Enabled)
                }) {
                    Some(FindingCode::FeatureGateRequired)
                } else if field.admission != FieldAdmission::Typed {
                    Some(FindingCode::UnadmittedField)
                } else {
                    None
                };
                if let Some(code) = code {
                    let mut f = Finding::error(code, Phase::Validation).for_resource(document.id);
                    f.path = path;
                    findings.push(f);
                }
            }
        } else {
            findings.push(
                Finding::warning(
                    if declaration(&identity.gvk).is_some() {
                        FindingCode::UnadmittedKind
                    } else {
                        FindingCode::UnknownKind
                    },
                    Phase::Validation,
                )
                .for_resource(document.id),
            );
        }
        validate_native(document, &tree, &identity, target, intent, &context, &mut findings);
    }
    findings.into_vec()
}
fn validate_source_fields(
    tree: &TreeNode,
    gvk: &crate::model::GroupVersionKind,
    resource: ResourceId,
    target: &TargetProfile,
    findings: &mut ProcessingReport,
) {
    let processing = findings.processing().clone();
    crate::capability::source_field_findings(
        tree,
        gvk,
        target,
        &processing,
        Phase::Validation,
        &mut crate::registry::ResourceFindingSink {
            sink: findings,
            resource,
        },
    );
}

fn validate_api(
    identity: &crate::model::ResourceIdentity,
    id: ResourceId,
    target: &TargetProfile,
    findings: &mut ProcessingReport,
) {
    if let Some(decl) = declaration(&identity.gvk) {
        if !(decl.first..=decl.last).contains(&target.kubernetes.minor()) {
            findings.push(Finding::error(FindingCode::UnavailableApi, Phase::Validation).for_resource(id));
        }
    } else if crate::capability::builtin_scope(&identity.gvk).is_some() {
        findings.push(Finding::error(FindingCode::UnavailableApi, Phase::Validation).for_resource(id));
    } else if identity.scope == crate::model::ResourceScope::Unknown {
        findings.push(Finding::warning(FindingCode::ScopeUnknown, Phase::Validation).for_resource(id));
    }
}
fn validate_native(
    document: &crate::model::ResourceDocument,
    tree: &TreeNode,
    identity: &crate::model::ResourceIdentity,
    target: &TargetProfile,
    intent: NativeValidationIntent,
    context: &crate::registry::EncodeContext<'_>,
    findings: &mut ProcessingReport,
) {
    if findings.failed() {
        return;
    }
    if let Some(decode) = document.decode {
        match decode(
            tree,
            &document.evidence,
            &crate::registry::DecodeContext {
                gvk: &identity.gvk,
                scope: identity.scope,
                fields: context.fields(Phase::Validation),
            },
        ) {
            Ok(resource) => {
                let mut sink = crate::registry::ResourceFindingSink {
                    sink: findings,
                    resource: document.id,
                };
                resource.validate(
                    &ValidationContext {
                        intent,
                        target,
                        fields: context.fields(Phase::Validation),
                    },
                    &mut sink,
                );
            }
            Err(errors) => findings.extend(errors.into_iter().map(|finding| finding.for_resource(document.id))),
        }
    }
}
fn bounded_json(node: &TreeNode, out: &mut String, processing: &NativeOperationBudget) -> Result<(), Finding> {
    // Charge the scan before inspecting bytes. serde_json preserves UTF-8 and only
    // expands JSON escapes; its temporary quoted string shares the 2x allowance.
    fn quoted_len(value: &str, processing: &NativeOperationBudget) -> Result<usize, Finding> {
        processing.work(value.len(), Phase::Generation)?;
        value.bytes().try_fold(2usize, |total, byte| {
            let bytes = match byte {
                b'"' | b'\\' | b'\x08' | b'\x0c' | b'\n' | b'\r' | b'\t' => 2,
                0..=0x1f => 6,
                _ => 1,
            };
            total
                .checked_add(bytes)
                .ok_or_else(|| processing.fail(Phase::Generation))
        })
    }
    // Keep the original conservative serialization work bound, independently
    // of the tighter output capacity/payload bound.
    fn bound(node: &TreeNode, processing: &NativeOperationBudget) -> Result<(usize, usize), Finding> {
        processing.work(1, Phase::Generation)?;
        let fail = || processing.fail(Phase::Generation);
        match &node.value {
            TreeValue::String(value) => Ok((
                quoted_len(value, processing)?,
                value
                    .len()
                    .checked_mul(6)
                    .and_then(|bytes| bytes.checked_add(2))
                    .ok_or_else(fail)?,
            )),
            TreeValue::Number(value) => Ok((value.len(), value.len())),
            TreeValue::Mapping(entries) => entries.iter().try_fold((2usize, 2usize), |(total, work), (key, node)| {
                let key_bytes = quoted_len(key, processing)?.checked_add(2).ok_or_else(fail)?;
                let key_work = key
                    .len()
                    .checked_mul(6)
                    .and_then(|bytes| bytes.checked_add(4))
                    .ok_or_else(fail)?;
                let (child_bytes, child_work) = bound(node, processing)?;
                Ok((
                    total
                        .checked_add(key_bytes)
                        .and_then(|n| n.checked_add(child_bytes))
                        .ok_or_else(fail)?,
                    work.checked_add(key_work)
                        .and_then(|n| n.checked_add(child_work))
                        .ok_or_else(fail)?,
                ))
            }),
            TreeValue::Sequence(items) => items.iter().try_fold((2usize, 2usize), |(total, work), node| {
                let (child_bytes, child_work) = bound(node, processing)?;
                Ok((
                    total
                        .checked_add(1)
                        .and_then(|n| n.checked_add(child_bytes))
                        .ok_or_else(fail)?,
                    work.checked_add(1)
                        .and_then(|n| n.checked_add(child_work))
                        .ok_or_else(fail)?,
                ))
            }),
            _ => Ok((5, 5)),
        }
    }
    let (upper, work) = bound(node, processing)?;
    let payload = upper.checked_mul(2).ok_or_else(|| processing.fail(Phase::Generation))?;
    processing.payload(payload, Phase::Generation)?;
    processing.work(work, Phase::Generation)?;
    out.reserve_exact(upper);
    json(node, out)
}
#[cfg(test)]
mod bounded_json_capacity_tests {
    use super::*;

    type TestResult = Result<(), Box<dyn std::error::Error>>;

    #[test]
    fn quoted_utf8_capacity_matches_json_escaping_and_keeps_two_buffers() -> TestResult {
        let controls: String = (0..=0x1f).map(char::from).collect();
        for value in [
            controls,
            "\"\\/\t\n\r".into(),
            "Grüße 世界 🙂\u{2028}\u{2029}".into(),
            String::new(),
        ] {
            let expected = serde_json::to_string(&value)?;
            let processing = NativeOperationBudget::new(NativeProcessingLimits {
                max_payload_bytes: expected.len() * 2,
                ..NativeProcessingLimits::default()
            });
            let mut out = String::new();
            bounded_json(&TreeNode::string(&value), &mut out, &processing)?;
            assert_eq!(out, expected);
            assert_eq!(processing.charged_payload_bytes(), expected.len() * 2);
            assert!(!processing.exhausted());
        }
        Ok(())
    }

    #[test]
    fn ordinary_strings_fit_tighter_payload_but_keep_conservative_work_and_scan() -> TestResult {
        let value = "é/plain".repeat(1024);
        let node = TreeNode::string(&value);
        let payload = (value.len() + 2) * 2;
        let work = 1 + value.len() + value.len() * 6 + 2;
        let limits = NativeProcessingLimits {
            max_payload_bytes: payload,
            max_processing_units: work,
            ..NativeProcessingLimits::default()
        };
        assert!(payload < (value.len() * 6 + 2) * 2);
        let processing = NativeOperationBudget::new(limits);
        let mut out = String::new();
        bounded_json(&node, &mut out, &processing)?;
        assert_eq!(out, serde_json::to_string(&value)?);
        for lower in [
            NativeProcessingLimits {
                max_payload_bytes: payload - 1,
                ..limits
            },
            NativeProcessingLimits {
                max_processing_units: work - 1,
                ..limits
            },
            NativeProcessingLimits {
                max_processing_units: value.len(),
                ..limits
            },
        ] {
            let processing = NativeOperationBudget::new(lower);
            let shared = processing.clone();
            let mut out = String::new();
            assert!(bounded_json(&node, &mut out, &processing).is_err());
            assert!(out.is_empty());
            assert!(shared.exhausted());
            assert!(bounded_json(&TreeNode::string(""), &mut out, &shared).is_err());
        }
        Ok(())
    }

    #[test]
    fn mapping_keys_sequences_and_number_spelling_keep_existing_output() -> TestResult {
        let node = TreeNode::mapping(vec![
            (
                "z\n".into(),
                TreeNode::new(TreeValue::Sequence(vec![
                    TreeNode::new(TreeValue::Bool(true)),
                    TreeNode::new(TreeValue::Null),
                    TreeNode::new(TreeValue::Number("1.2300e+02".into())),
                ])),
            ),
            ("ä\"".into(), TreeNode::string("\\世界")),
        ]);
        let mut expected = String::new();
        json(&node, &mut expected)?;
        let processing = NativeOperationBudget::new(NativeProcessingLimits {
            // One extra comma per container and conservative true/null lengths.
            max_payload_bytes: (expected.len() + 5) * 2,
            ..NativeProcessingLimits::default()
        });
        let mut out = String::new();
        bounded_json(&node, &mut out, &processing)?;
        assert_eq!(out, "{\"z\\n\":[true,null,1.2300e+02],\"ä\\\"\":\"\\\\世界\"}");
        assert_eq!(out, expected);
        assert!(!processing.exhausted());
        Ok(())
    }

    #[test]
    fn tagged_values_and_duplicate_keys_still_fail() {
        for node in [
            TreeNode::new(TreeValue::Tagged("tag".into(), Box::new(TreeNode::string("x")))),
            TreeNode::mapping(vec![
                ("a".into(), TreeNode::string("x")),
                ("a".into(), TreeNode::string("y")),
            ]),
        ] {
            let processing = NativeOperationBudget::new(NativeProcessingLimits::default());
            assert!(bounded_json(&node, &mut String::new(), &processing).is_err());
            assert!(!processing.exhausted());
        }
    }
}

pub(crate) fn field_nodes<'a>(tree: &'a TreeNode, pointer: &str) -> Vec<&'a TreeNode> {
    let Ok(path) = FieldPath::parse(pointer) else {
        return Vec::new();
    };
    let mut nodes = vec![tree];
    for segment in &path.0 {
        let mut next = Vec::new();
        for node in nodes {
            if segment == "*" {
                match &node.value {
                    TreeValue::Sequence(items) => next.extend(items),
                    TreeValue::Mapping(entries) => next.extend(entries.iter().map(|(_, v)| v)),
                    _ => {}
                }
            } else if let Some(value) = node.get(segment) {
                next.push(value);
            }
        }
        nodes = next;
    }
    nodes
}
/// Generate current native values without files, processes, clusters, or implicit migration.
/// # Errors
/// Blocks invalid targets/identities, unavailable APIs/fields, opaque/private output, and lossy edits.
pub fn generate(
    resources: &ResourceSet,
    target: &TargetProfile,
    format: OutputFormat,
    options: &GenerationOptions,
) -> Result<GeneratedArtifact, Vec<Finding>> {
    let processing = resources.operation(options.processing);
    let construction = resources.encoding(Some(target), processing.clone());
    let mut findings = ProcessingReport::from_report(
        validate_in(resources, target, options.validation_intent, processing.clone()),
        processing.clone(),
        Phase::Generation,
    );
    let mut trees = BTreeMap::new();
    for doc in &resources.documents {
        if findings.failed() {
            break;
        }
        let context = construction.for_source(*doc.evidence.limits());
        let projection = match doc.project_in(Some(target), Some(&context)) {
            Ok(projection) => projection,
            Err(errors) => {
                findings.extend(errors);
                continue;
            }
        };
        findings.extend(projection.findings);
        let mut tree = projection.tree;
        if let Err(error) = apply_observation_output(
            doc,
            &mut tree,
            projection.observations,
            options,
            &mut findings,
            &processing,
        ) {
            findings.push(error);
            break;
        }
        preserve_access_mode_findings(doc, &tree, &projection.occurrences, options, &processing, &mut findings);
        apply_generation_admission(doc, &tree, options, &processing, &mut findings);
        let mut protected_paths = Vec::new();
        if let Some(resource) = &projection.resource {
            resource.collect_protected_paths(&context, &mut protected_paths);
        }
        let codec_protected = protected_paths
            .iter()
            .any(|path| tree.get_path(path).is_some_and(|node| node.value != TreeValue::Null));
        if options.protected_output == ProtectedOutput::Deny
            && (codec_protected
                || protected(&tree)
                || doc.original_identity.scope.namespaced().is_none()
                || matches!(
                    doc.original_identity.scope,
                    crate::model::ResourceScope::CrdResolved { .. }
                ))
        {
            findings.push(Finding::error(FindingCode::ProtectedOutputDenied, Phase::Generation).for_resource(doc.id));
        }
        if contains_tags(&tree) {
            findings.push(Finding::error(FindingCode::UnsupportedScalar, Phase::Generation).for_resource(doc.id));
        }
        trees.insert(doc.id, tree);
    }
    let mut wrappers = prepare_wrappers(resources, options, &processing, &mut findings);
    if findings.failed() || has_errors(&findings) {
        return Err(findings.into_vec());
    }
    let roots = match output_roots(resources, options.collections, &mut trees, &mut wrappers, &processing) {
        Ok(roots) => roots,
        Err(finding) => {
            findings.push(finding);
            return Err(findings.into_vec());
        }
    };
    let bytes = match serialize_roots(roots, format, options.json_shape, &processing) {
        Ok(bytes) => bytes,
        Err(finding) => {
            findings.push(finding);
            return Err(findings.into_vec());
        }
    };
    if let Err(finding) = processing.payload(bytes.len(), Phase::Generation) {
        findings.push(finding);
        return Err(findings.into_vec());
    }
    Ok(GeneratedArtifact {
        format,
        bytes: Arc::from(bytes.into_bytes()),
        findings: findings.into_vec(),
    })
}
/// Preservation changes the outcome severity, never finite admission or retained source evidence.
fn preserve_access_mode_findings(
    document: &crate::model::ResourceDocument,
    tree: &TreeNode,
    occurrences: &crate::syntax::NativeOccurrences,
    options: &GenerationOptions,
    processing: &NativeOperationBudget,
    findings: &mut ProcessingReport,
) {
    if options.opaque_fields != OpaqueFieldPolicy::PreserveWithFinding
        || options.protected_output != ProtectedOutput::Include
    {
        return;
    }
    for finding in findings.entries_mut() {
        if processing.work(1, Phase::Generation).is_err() {
            return;
        }
        if finding.code != FindingCode::UnadmittedField || finding.resource != Some(document.id) {
            continue;
        }
        let Some(path) = &finding.path else {
            continue;
        };
        let Some((_, parents)) = path.0.split_last() else {
            continue;
        };
        if parents.last().is_none_or(|segment| segment != "accessModes") {
            continue;
        }
        if processing
            .payload_array::<String>(parents.len(), Phase::Generation)
            .is_err()
            || parents
                .iter()
                .any(|segment| processing.payload(segment.len(), Phase::Generation).is_err())
        {
            return;
        }
        let collection = FieldPath(parents.to_vec());
        let Some(value) = tree.get_path(path).and_then(TreeNode::as_str) else {
            continue;
        };
        if crate::value::EstablishedVolumeAccessMode::selected(value).is_some() {
            continue;
        }
        match supplied_access_mode_occurrence(document, tree, occurrences, &collection, processing) {
            Ok(true) => finding.severity = Severity::Warning,
            Ok(false) => {}
            Err(_) => return,
        }
    }
}
fn supplied_access_mode_occurrence(
    document: &crate::model::ResourceDocument,
    tree: &TreeNode,
    occurrences: &crate::syntax::NativeOccurrences,
    path: &FieldPath,
    processing: &NativeOperationBudget,
) -> Result<bool, Finding> {
    processing.work(1, Phase::Generation)?;
    if !matches!(document.evidence.origin, crate::source::EvidenceOrigin::Supplied(_)) {
        return Ok(false);
    }
    for edit in &document.edits {
        processing.work(1, Phase::Generation)?;
        let edited = match edit {
            FieldEdit::Set { path, .. } | FieldEdit::Remove { path } => path,
        };
        if path.0.starts_with(&edited.0) || edited.0.starts_with(&path.0) {
            return Ok(false);
        }
    }
    let (Some(before), Some(after)) = (document.original.get_path(path), tree.get_path(path)) else {
        return Ok(false);
    };
    if before.as_sequence().is_none() || after.as_sequence().is_none() {
        return Ok(false);
    }
    let context = BudgetedMergeContext {
        native: MergeContext {
            gvk: Some(&document.original_identity.gvk),
            target: None,
        },
        processing,
        phase: Phase::Generation,
    };
    if !merge_semantic_eq(before, after, context)? {
        return Ok(false);
    }
    // Mutable holders contribute only candidates. Immutable per-document/path
    // anchors plus the actual original/effective complete sequence authorize them.
    let mut native_bound = false;
    for original_path in document.original_occurrences.keys() {
        processing.work(1, Phase::Generation)?;
        for segment in original_path.0.iter().chain(&path.0) {
            processing.work(segment.len().saturating_add(1), Phase::Generation)?;
        }
        if original_path == path {
            native_bound = true;
            break;
        }
    }
    if native_bound {
        if !sealed_occurrence_matches(&document.original_occurrences, occurrences, path, processing)? {
            return Ok(false);
        }
        for ancestor in document.original_occurrences.keys() {
            processing.work(1, Phase::Generation)?;
            for segment in ancestor.0.iter().chain(&path.0) {
                processing.work(segment.len().saturating_add(1), Phase::Generation)?;
            }
            if ancestor != path
                && path.0.starts_with(&ancestor.0)
                && !sealed_occurrence_matches(&document.original_occurrences, occurrences, ancestor, processing)?
            {
                return Ok(false);
            }
        }
    }
    supplied_access_mode_path_occurrence(&document.original, tree, path, native_bound, context)
}

fn supplied_access_mode_path_occurrence(
    original: &TreeNode,
    tree: &TreeNode,
    path: &FieldPath,
    native_bound: bool,
    context: BudgetedMergeContext<'_>,
) -> Result<bool, Finding> {
    // Bind nested occurrences from immutable source/destination trees. No mutable
    // native holder name, cached origin, or blanket ancestor-value equality is authority.
    let processing = context.processing;
    let mut before = original;
    let mut after = tree;
    for segment in &path.0 {
        processing.work(1, Phase::Generation)?;
        if let Some(original_items) = before.as_sequence() {
            let Some(effective_items) = after.as_sequence() else {
                return Ok(false);
            };
            processing.work(segment.len(), Phase::Generation)?;
            let Ok(index) = segment.parse::<usize>() else {
                return Ok(false);
            };
            let (Some(original), Some(effective)) = (original_items.get(index), effective_items.get(index)) else {
                return Ok(false);
            };
            let Some(position) = original.start else {
                return Ok(false);
            };
            if !native_bound && effective.start != Some(position) {
                return Ok(false);
            }
            for items in [Some(original_items), (!native_bound).then_some(effective_items)]
                .into_iter()
                .flatten()
            {
                let mut matches = 0;
                for item in items {
                    processing.work(1, Phase::Generation)?;
                    if item.start == Some(position) {
                        matches += 1;
                    }
                }
                if matches != 1 {
                    return Ok(false);
                }
            }
            before = original;
            after = effective;
        } else {
            let (Some(original), Some(effective)) = (context.get(before, segment)?, context.get(after, segment)?)
            else {
                return Ok(false);
            };
            before = original;
            after = effective;
        }
    }
    Ok(true)
}

fn sealed_occurrence_matches(
    originals: &crate::syntax::NativeOccurrences,
    candidates: &crate::syntax::NativeOccurrences,
    path: &FieldPath,
    processing: &NativeOperationBudget,
) -> Result<bool, Finding> {
    for table in [originals, candidates] {
        for key in table.keys() {
            processing.work(1, Phase::Generation)?;
            for segment in key.0.iter().chain(&path.0) {
                processing.work(segment.len().saturating_add(1), Phase::Generation)?;
            }
        }
    }
    let (Some(original), Some(candidate)) = (originals.get(path), candidates.get(path)) else {
        return Ok(false);
    };
    if !original.same(candidate) {
        return Ok(false);
    }
    for table in [originals, candidates] {
        let mut matches = 0;
        for token in table.values() {
            processing.work(1, Phase::Generation)?;
            if original.same(token) {
                matches += 1;
            }
        }
        if matches != 1 {
            return Ok(false);
        }
    }
    Ok(true)
}

fn output_roots(
    resources: &ResourceSet,
    collections: CollectionOutput,
    trees: &mut BTreeMap<ResourceId, TreeNode>,
    wrappers: &mut BTreeMap<crate::model::ListId, TreeNode>,
    processing: &NativeOperationBudget,
) -> Result<Vec<TreeNode>, Finding> {
    processing.payload_array::<&crate::model::ResourceDocument>(resources.documents.len(), Phase::Generation)?;
    for tree in trees.values() {
        crate::model::charge_identity(tree, processing, Phase::Generation)?;
    }
    let mut ordered: Vec<_> = resources.documents.iter().collect();
    ordered.sort_by_cached_key(|doc| {
        trees
            .get(&doc.id)
            .and_then(|tree| crate::model::identity(tree, doc.original_identity.scope).ok())
            .map(|identity| (identity.gvk, identity.scope, identity.namespace, identity.name, doc.id))
    });
    let root_count = resources
        .documents
        .len()
        .checked_add(resources.lists.len())
        .ok_or_else(|| processing.fail(Phase::Generation))?;
    processing.payload_array::<TreeNode>(root_count, Phase::Generation)?;
    let mut roots = Vec::new();
    if collections == CollectionOutput::PreserveWrappers {
        for list in resources.lists.iter().filter(|list| list.collection.is_none()) {
            roots.push(rewrap(resources, list.id, trees, wrappers, processing)?);
        }
        roots.extend(
            ordered
                .iter()
                .filter(|doc| doc.collection.is_none())
                .filter_map(|doc| trees.remove(&doc.id)),
        );
    } else {
        roots.extend(ordered.iter().filter_map(|doc| trees.remove(&doc.id)));
    }
    Ok(roots)
}

fn serialize_roots(
    mut roots: Vec<TreeNode>,
    format: OutputFormat,
    shape: JsonShape,
    processing: &NativeOperationBudget,
) -> Result<String, Finding> {
    let mut bytes = String::new();
    match format {
        OutputFormat::Json => {
            let root = match shape {
                JsonShape::SingleResource => {
                    if roots.len() != 1 {
                        return Err(Finding::error(FindingCode::MalformedDocument, Phase::Generation));
                    }
                    roots.remove(0)
                }
                JsonShape::KubernetesList => list_tree(roots),
            };
            bounded_json(&root, &mut bytes, processing)?;
            append_output(&mut bytes, "\n", processing)?;
        }
        OutputFormat::Yaml => {
            for root in roots {
                append_output(&mut bytes, "---\n", processing)?;
                bounded_json(&root, &mut bytes, processing)?;
                append_output(&mut bytes, "\n", processing)?;
            }
        }
    }
    Ok(bytes)
}
fn append_output(out: &mut String, text: &str, processing: &NativeOperationBudget) -> Result<(), Finding> {
    processing.payload(text.len(), Phase::Generation)?;
    processing.work(text.len(), Phase::Generation)?;
    out.reserve_exact(text.len());
    out.push_str(text);
    Ok(())
}
fn prepare_wrappers(
    resources: &ResourceSet,
    options: &GenerationOptions,
    processing: &NativeOperationBudget,
    findings: &mut ProcessingReport,
) -> BTreeMap<crate::model::ListId, TreeNode> {
    let mut wrappers = BTreeMap::new();
    for list in &resources.lists {
        if findings.failed() {
            break;
        }
        // Resource projections already own each replacement item. Retain only
        // this wrapper's fields; copying its source items would duplicate all
        // descendants, again at every enclosing List level.
        let mut tree = match wrapper_header(&list.original, processing) {
            Ok(tree) => tree,
            Err(finding) => {
                findings.push(finding);
                break;
            }
        };
        let unknown = wrapper_unknown_paths(&tree, list, processing, findings);
        if findings.failed() {
            break;
        }
        if options.opaque_fields == OpaqueFieldPolicy::Block {
            if let Some(path) = &unknown {
                findings.push(wrapper_finding(
                    list,
                    FindingCode::OpaqueOutputDenied,
                    Phase::Generation,
                    path.clone(),
                    true,
                ));
            }
        }
        if options.protected_output == ProtectedOutput::Deny
            && (unknown.is_some()
                || tree
                    .get("metadata")
                    .and_then(|metadata| metadata.get("continue"))
                    .is_some_and(|node| node.value != TreeValue::Null))
        {
            findings.push(wrapper_finding(
                list,
                FindingCode::ProtectedOutputDenied,
                Phase::Generation,
                FieldPath::default(),
                true,
            ));
        }
        let tagged = match wrapper_contains_tags(&list.original, processing) {
            Ok(tagged) => tagged,
            Err(finding) => {
                findings.push(finding);
                break;
            }
        };
        if tagged {
            findings.push(wrapper_finding(
                list,
                FindingCode::UnsupportedScalar,
                Phase::Generation,
                FieldPath::default(),
                true,
            ));
        }
        if options.intent == OutputIntent::AuthoredIntent {
            let begin = findings.len();
            strip_wrapper_observed(&mut tree, findings);
            for finding in &mut findings.entries_mut()[begin..] {
                finding.wrapper = Some(WrapperSubject {
                    source: list.source,
                    list: list.id,
                });
                finding.source = finding
                    .path
                    .as_ref()
                    .and_then(|path| list.original.get_path(path))
                    .and_then(|node| node.start);
            }
        }
        if options.collections == CollectionOutput::Flatten {
            if let Some(entries) = tree.as_mapping() {
                for (key, _) in entries {
                    if !matches!(key.as_str(), "apiVersion" | "kind" | "items") {
                        findings.push(wrapper_finding(
                            list,
                            FindingCode::CollectionFieldRemoved,
                            Phase::Generation,
                            FieldPath(vec![key.clone()]),
                            false,
                        ));
                    }
                }
            }
        }
        wrappers.insert(list.id, tree);
    }
    wrappers
}

/// Copy wrapper fields and source positions once, reserving an empty items
/// slot. Source item count/order remain in the immutable `ListDocument`; effective
/// resource values are moved into that slot during reconstruction.
fn wrapper_header(original: &TreeNode, processing: &NativeOperationBudget) -> Result<TreeNode, Finding> {
    let phase = Phase::Generation;
    processing.work(1, phase)?;
    let TreeValue::Mapping(entries) = &original.value else {
        return Err(conflict());
    };
    processing.payload_array::<TreeNode>(1, phase)?;
    processing.payload_array::<(String, TreeNode)>(entries.len(), phase)?;
    let mut header = Vec::new();
    header
        .try_reserve_exact(entries.len())
        .map_err(|_| processing.fail(phase))?;
    for (key, value) in entries {
        processing.work(key.len().checked_add(1).ok_or_else(|| processing.fail(phase))?, phase)?;
        processing.payload(key.len(), phase)?;
        let value = if key == "items" {
            if value.as_sequence().is_none() {
                return Err(conflict());
            }
            TreeNode {
                value: TreeValue::Sequence(Vec::new()),
                start: value.start,
            }
        } else {
            processing.tree_copy(value, phase)?;
            value.clone()
        };
        header.push((key.clone(), value));
    }
    Ok(TreeNode {
        value: TreeValue::Mapping(header),
        start: original.start,
    })
}

// The original wrapper, including its source items, still participates in tag
// denial. Charge each visited node now that no incidental whole-wrapper copy
// supplies its traversal allowance.
fn wrapper_contains_tags(tree: &TreeNode, processing: &NativeOperationBudget) -> Result<bool, Finding> {
    processing.work(1, Phase::Generation)?;
    match &tree.value {
        TreeValue::Tagged(..) => Ok(true),
        TreeValue::Mapping(entries) => {
            for (_, child) in entries {
                if wrapper_contains_tags(child, processing)? {
                    return Ok(true);
                }
            }
            Ok(false)
        }
        TreeValue::Sequence(items) => {
            for child in items {
                if wrapper_contains_tags(child, processing)? {
                    return Ok(true);
                }
            }
            Ok(false)
        }
        _ => Ok(false),
    }
}

fn list_tree(items: Vec<TreeNode>) -> TreeNode {
    TreeNode::mapping(vec![
        ("apiVersion".into(), TreeNode::string("v1")),
        ("kind".into(), TreeNode::string("List")),
        ("items".into(), TreeNode::new(TreeValue::Sequence(items))),
    ])
}
fn rewrap(
    resources: &ResourceSet,
    id: crate::model::ListId,
    trees: &mut BTreeMap<ResourceId, TreeNode>,
    wrappers: &mut BTreeMap<crate::model::ListId, TreeNode>,
    processing: &NativeOperationBudget,
) -> Result<TreeNode, Finding> {
    processing.work(resources.lists.len(), Phase::Generation)?;
    let list = resources.lists.iter().find(|list| list.id == id).ok_or_else(conflict)?;
    let result = (|| {
        let mut wrapper = wrappers.remove(&id).ok_or_else(conflict)?;
        let Some(items) = list.original.get("items").and_then(TreeNode::as_sequence) else {
            return Err(conflict());
        };
        processing.payload_array::<TreeNode>(items.len(), Phase::Generation)?;
        let mut current = Vec::new();
        current
            .try_reserve_exact(items.len())
            .map_err(|_| processing.fail(Phase::Generation))?;
        for index in 0..items.len() {
            processing.work(
                resources
                    .lists
                    .len()
                    .checked_add(resources.documents.len())
                    .and_then(|n| n.checked_add(1))
                    .ok_or_else(|| processing.fail(Phase::Generation))?,
                Phase::Generation,
            )?;
            if let Some(nested) = resources.lists.iter().find(|l| {
                l.collection
                    .as_ref()
                    .is_some_and(|path| path.items.last() == Some(&(id, index)))
            }) {
                current.push(rewrap(resources, nested.id, trees, wrappers, processing)?);
            } else if let Some(doc) = resources.documents.iter().find(|d| {
                d.collection
                    .as_ref()
                    .is_some_and(|path| path.items.last() == Some(&(id, index)))
            }) {
                current.push(trees.remove(&doc.id).ok_or_else(conflict)?);
            } else {
                return Err(conflict());
            }
        }
        set_child(&mut wrapper, "items", Some(TreeNode::new(TreeValue::Sequence(current))))?;
        Ok(wrapper)
    })();
    result.map_err(|mut finding: Finding| {
        if finding.code == FindingCode::LimitExceeded {
            return finding;
        }
        if finding.wrapper.is_none() {
            finding = finding.for_wrapper(WrapperSubject {
                source: list.source,
                list: id,
            });
        }
        if finding.source.is_none() {
            finding.source = list.original.start;
        }
        finding
    })
}
fn strip_wrapper_observed(tree: &mut TreeNode, findings: &mut ProcessingReport) {
    strip_observation_paths(tree, None, &crate::source::list_observation_paths(), findings);
}

