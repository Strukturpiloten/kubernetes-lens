/// Reviewed scalar default spellings, separate from immutable schema enum evidence.
pub(crate) fn source_default_enum(
    gvk: &GroupVersionKind,
    node: &crate::syntax::TreeNode,
    path: &crate::diagnostic::FieldPath,
) -> bool {
    if gvk.group.is_some() || gvk.version != "v1" || node.as_str() != Some("") {
        return false;
    }
    match (gvk.kind.as_str(), path.0.as_slice()) {
        ("Service", [spec, field]) => spec == "spec" && matches!(field.as_str(), "type" | "sessionAffinity"),
        ("Service", [spec, ports, index, protocol]) => {
            spec == "spec" && ports == "ports" && protocol == "protocol" && index.parse::<usize>().is_ok()
        }
        ("Endpoints", [subsets, subset, ports, index, protocol]) => {
            subsets == "subsets"
                && ports == "ports"
                && protocol == "protocol"
                && subset.parse::<usize>().is_ok()
                && index.parse::<usize>().is_ok()
        }
        _ => false,
    }
}
