fn version(minor: u8) -> KubernetesVersion {
    KubernetesVersion::new(1, minor).unwrap_or(KubernetesVersion::MAX)
}
fn field(
    path: &'static str,
    first: u8,
    last: u8,
    gate: Option<FeatureGateId>,
    merge: MergeStrategy,
) -> FieldCapability {
    FieldCapability {
        path,
        since: version(first),
        removed: (last < 37).then(|| version(last + 1)),
        deprecated: None,
        feature_gate: gate,
        admission: if path.ends_with("/deprecatedTopology") {
            FieldAdmission::PreserveOnly
        } else {
            FieldAdmission::Typed
        },
        merge,
        semantic_note: if path.ends_with("/deprecatedTopology") {
            Some("Server-owned topology is retained; desired writes are ignored by the native API.")
        } else {
            None
        },
    }
}
